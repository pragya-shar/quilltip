/**
 * Generates the TypeScript bindings for the v2 contracts
 * (docs/architecture/v2/06-app-integration.md, section 6.6).
 *
 * The bindings come from the contract spec inside each built Wasm, through
 * the generator in the pinned `@stellar/stellar-sdk` (`stellar-js generate`).
 * The Stellar CLI's own `contract bindings typescript` command is deprecated
 * in favour of this generator. The command is offline: it reads local Wasm
 * files and contacts no network.
 *
 * Usage:
 *   bun scripts/contracts/bindings.ts --wasm-dir <dir>          write lib/stellar/v2/bindings
 *   bun scripts/contracts/bindings.ts --wasm-dir <dir> --check  fail when the committed bindings are stale
 *
 * `<dir>` holds quilltip_core.wasm, quilltip_tab.wasm and quilltip_article_nft.wasm,
 * for example the output of scripts/contracts/build-reproducible.sh.
 */
import { spawnSync } from 'child_process'
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
  mkdirSync,
} from 'fs'
import { tmpdir } from 'os'
import { join, resolve } from 'path'

export const CONTRACTS = [
  { name: 'core', wasm: 'quilltip_core.wasm', className: 'QuillTipCore' },
  { name: 'tab', wasm: 'quilltip_tab.wasm', className: 'QuillTipTab' },
  {
    name: 'nft',
    wasm: 'quilltip_article_nft.wasm',
    className: 'QuillTipArticleNft',
  },
] as const

const GENERATED_FILES = ['client.ts', 'types.ts', 'index.ts'] as const

// The generated clients do not use `override`, which the repository's
// `noImplicitOverride` requires; their exported types still reach callers.
const HEADER =
  '// Generated by scripts/contracts/bindings.ts from the contract Wasm. Do not edit.\n// @ts-nocheck\n'

const repoRoot = resolve(__dirname, '../..')
export const BINDINGS_DIR = join(repoRoot, 'lib/stellar/v2/bindings')

function generate(wasmPath: string, className: string): Map<string, string> {
  const out = mkdtempSync(join(tmpdir(), 'quilltip-bindings-'))
  try {
    const result = spawnSync(
      join(repoRoot, 'node_modules/.bin/stellar-js'),
      [
        'generate',
        '--wasm',
        wasmPath,
        '--output-dir',
        out,
        '--contract-name',
        className,
        '--overwrite',
      ],
      { encoding: 'utf8' }
    )
    if (result.status !== 0) {
      throw new Error(
        `stellar-js generate failed for ${wasmPath}:\n${result.stderr}${result.stdout}`
      )
    }
    const files = new Map<string, string>()
    for (const file of GENERATED_FILES) {
      files.set(file, HEADER + readFileSync(join(out, 'src', file), 'utf8'))
    }
    return files
  } finally {
    rmSync(out, { recursive: true, force: true })
  }
}

function main(argv: string[]): number {
  const dirIndex = argv.indexOf('--wasm-dir')
  const check = argv.includes('--check')
  if (dirIndex === -1 || !argv[dirIndex + 1]) {
    console.error(
      'Usage: bun scripts/contracts/bindings.ts --wasm-dir <dir> [--check]'
    )
    return 2
  }
  const wasmDir = resolve(argv[dirIndex + 1] as string)
  const stale: string[] = []
  for (const c of CONTRACTS) {
    const wasmPath = join(wasmDir, c.wasm)
    if (!existsSync(wasmPath)) {
      console.error(`Missing ${wasmPath}`)
      return 2
    }
    const files = generate(wasmPath, c.className)
    const dir = join(BINDINGS_DIR, c.name)
    if (check) {
      const committed = existsSync(dir) ? readdirSync(dir).sort() : []
      if (committed.join(',') !== [...GENERATED_FILES].sort().join(','))
        stale.push(`${c.name}/ (file set)`)
      for (const [file, text] of files) {
        const path = join(dir, file)
        if (!existsSync(path) || readFileSync(path, 'utf8') !== text)
          stale.push(`${c.name}/${file}`)
      }
    } else {
      rmSync(dir, { recursive: true, force: true })
      mkdirSync(dir, { recursive: true })
      for (const [file, text] of files) writeFileSync(join(dir, file), text)
      console.log(`Wrote lib/stellar/v2/bindings/${c.name}`)
    }
  }
  if (stale.length > 0) {
    console.error(
      `Stale contract bindings: ${stale.join(', ')}.\nRegenerate with: bun scripts/contracts/bindings.ts --wasm-dir <built wasm dir>`
    )
    return 1
  }
  if (check) console.log('Contract bindings match the built Wasm.')
  return 0
}

if (import.meta.main) process.exit(main(process.argv.slice(2)))
